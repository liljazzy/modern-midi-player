"""Build the Windows installer:  dist/ModernMidiPlayer-Setup-<version>.exe

Works on Windows (with NSIS installed: https://nsis.sourceforge.io) or on
Linux/macOS with a native makensis.  Requires Pillow for the artwork.

    python installer/build_installer.py [--makensis PATH]

What it bundles
  * the app (midiplayer package, demos, SoundFont)
  * a private 64-bit CPython (python-build-standalone) - no system Python needed
  * FluidSynth DLLs (high-quality software synth)
PySide6 is downloaded by the installer at install time (pip).
"""
import argparse
import hashlib
import os
import shutil
import subprocess
import sys
import tarfile
import urllib.request
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
BUILD = os.path.join(HERE, "build")
STAGE = os.path.join(BUILD, "stage")
CACHE = os.path.join(HERE, "cache")
DIST = os.path.join(ROOT, "dist")

PYTHON_URL = ("https://github.com/astral-sh/python-build-standalone/releases/download/20241016/"
              "cpython-3.12.7+20241016-x86_64-pc-windows-msvc-install_only.tar.gz")
FLUID_URL = "https://github.com/FluidSynth/fluidsynth/releases/download/v2.3.4/fluidsynth-2.3.4-win10-x64.zip"

sys.path.insert(0, ROOT)
from midiplayer import __version__  # noqa: E402

